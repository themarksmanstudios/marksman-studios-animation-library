"""Place a 64-bone Marksman target armature in an open T-pose as its rest pose.

Run with Blender 5.0.1 on a copy first. The target rig is identified by the
humanoid bone names rather than an object name so each animation scene can use
the same routine.
"""
import bpy
import json
import os
from mathutils import Matrix, Vector


def _target_rig():
    required = {"upper_arm.L", "upper_arm.R", "forearm.L", "forearm.R", "hand.L", "hand.R"}
    scene_objects = set(bpy.context.scene.objects)
    candidates = [obj for obj in scene_objects if obj.type == "ARMATURE" and required.issubset(obj.data.bones.keys())]
    if not candidates:
        raise RuntimeError("Could not find the studio mannequin armature with upper_arm/forearm/hand L/R bones.")
    # The mannequin is the armature driving the scene character mesh. Other
    # 64-bone rigs may be controls or older mannequin data with no mesh bound.
    def score(rig):
        return sum(10 for mesh in scene_objects if mesh.type == "MESH" and (
            mesh.parent == rig or any(mod.type == "ARMATURE" and mod.object == rig for mod in mesh.modifiers)
        ))
    return max(candidates, key=score)


def _set_pose_matrix(rig, name, head, direction):
    bone = rig.data.bones[name]
    pose_bone = rig.pose.bones[name]
    base_rotation = bone.matrix_local.to_quaternion()
    local_axis = bone.matrix_local.to_3x3() @ Vector((0.0, 1.0, 0.0))
    rotation = local_axis.normalized().rotation_difference(direction.normalized()) @ base_rotation
    pose_bone.rotation_mode = "QUATERNION"
    pose_bone.matrix = Matrix.LocRotScale(Vector(head), rotation, Vector((1.0, 1.0, 1.0)))
    bpy.context.view_layer.update()


def build_open_t_pose(rig):
    if rig.get("marksman_t_pose_rest_v1"):
        return False

    # A generated retarget action is regenerated by the production worker from
    # the source file after the shared template is updated. Remove it while
    # baking the new rest pose so it cannot override the pose channels here.
    if rig.animation_data:
        rig.animation_data.action = None
        for track in rig.animation_data.nla_tracks:
            for strip in track.strips:
                strip.mute = True

    for side in ("L", "R"):
        sign = 1.0 if side == "L" else -1.0
        outward = Vector((sign, 0.0, 0.0))
        lateral = Vector((0.0, 1.0, 0.0))
        shoulder = rig.data.bones[f"upper_arm.{side}"].head_local.copy()
        upper_length = rig.data.bones[f"upper_arm.{side}"].length
        forearm_length = rig.data.bones[f"forearm.{side}"].length
        hand_length = rig.data.bones[f"hand.{side}"].length
        elbow = shoulder + outward * upper_length
        wrist = elbow + outward * forearm_length
        hand_end = wrist + outward * hand_length

        for name, head, direction in (
            (f"upper_arm.{side}", shoulder, outward),
            (f"forearm.{side}", elbow, outward),
            (f"hand.{side}", wrist, outward),
        ):
            _set_pose_matrix(rig, name, head, direction)

        # Give each digit a straight outward chain while keeping the four
        # fingers spread across the palm. Thumb remains splayed away from the
        # fingers. Existing segment lengths and rig weights are preserved.
        finger_layout = (
            ("index", -0.031, 0.0),
            ("middle", -0.010, 0.0),
            ("ring", 0.011, 0.0),
            ("pinky", 0.031, 0.0),
        )
        for finger, lateral_offset, vertical_offset in finger_layout:
            palm_name = f"palm.{ {'index': '01', 'middle': '02', 'ring': '03', 'pinky': '04'}[finger] }.{side}"
            palm_len = rig.data.bones[palm_name].length
            palm_head = hand_end - outward * 0.025 + lateral * lateral_offset
            palm_tail = palm_head + outward * palm_len
            _set_pose_matrix(rig, palm_name, palm_head, outward)
            digit_head = palm_tail
            for segment in range(1, 4):
                digit_name = f"f_{finger}.{segment:02d}.{side}"
                if digit_name not in rig.data.bones:
                    continue
                digit_length = rig.data.bones[digit_name].length
                _set_pose_matrix(rig, digit_name, digit_head, outward)
                digit_head = digit_head + outward * digit_length

        thumb_direction = (outward + lateral * (-0.62 if side == "L" else 0.62) + Vector((0.0, 0.0, 0.25))).normalized()
        thumb_head = hand_end - outward * 0.028 - lateral * 0.018 - Vector((0.0, 0.0, 0.008))
        for segment in range(1, 4):
            thumb_name = f"thumb.{segment:02d}.{side}"
            if thumb_name not in rig.data.bones:
                continue
            thumb_length = rig.data.bones[thumb_name].length
            _set_pose_matrix(rig, thumb_name, thumb_head, thumb_direction)
            thumb_head = thumb_head + thumb_direction * thumb_length

    bpy.context.view_layer.update()
    evaluated = rig.evaluated_get(bpy.context.evaluated_depsgraph_get())
    key_bones = ["upper_arm.L", "forearm.L", "hand.L", "upper_arm.R", "forearm.R", "hand.R"]
    print("POSE_BEFORE_APPLY", json.dumps({name: {
        "head": [round(v, 3) for v in evaluated.pose.bones[name].head],
        "tail": [round(v, 3) for v in evaluated.pose.bones[name].tail],
    } for name in key_bones}))
    if os.environ.get("MARKSMAN_TPOSE_DEBUG_RENDER"):
        bpy.context.scene.render.filepath = os.environ["MARKSMAN_TPOSE_DEBUG_RENDER"]
        bpy.context.scene.render.resolution_percentage = 35
        bpy.ops.render.render(write_still=True)
    # Bake the live T-pose onto the skinned mesh before changing the rest
    # bones. Otherwise the armature modifier's original bind transform restores
    # the old A-pose when the pose channels are cleared by armature_apply.
    skinned_meshes = []
    for mesh in bpy.context.scene.objects:
        if mesh.type != "MESH":
            continue
        for modifier in list(mesh.modifiers):
            if modifier.type == "ARMATURE" and modifier.object == rig:
                settings = {
                    "name": modifier.name,
                    "use_vertex_groups": modifier.use_vertex_groups,
                    "use_bone_envelopes": modifier.use_bone_envelopes,
                    "use_deform_preserve_volume": modifier.use_deform_preserve_volume,
                    "show_viewport": modifier.show_viewport,
                    "show_render": modifier.show_render,
                }
                skinned_meshes.append((mesh, settings))
                bpy.context.view_layer.objects.active = mesh
                mesh.select_set(True)
                rig.select_set(False)
                bpy.ops.object.modifier_apply(modifier=modifier.name)

    bpy.context.view_layer.objects.active = rig
    rig.select_set(True)
    for obj in bpy.context.selected_objects:
        if obj != rig:
            obj.select_set(False)
    if rig.mode != "OBJECT":
        bpy.ops.object.mode_set(mode="OBJECT")
    bpy.ops.object.mode_set(mode="POSE")
    bpy.ops.pose.select_all(action="SELECT")
    bpy.ops.pose.armature_apply(selected=False)
    bpy.ops.object.mode_set(mode="OBJECT")
    for mesh, settings in skinned_meshes:
        modifier = mesh.modifiers.new(settings["name"], "ARMATURE")
        modifier.object = rig
        modifier.use_vertex_groups = settings["use_vertex_groups"]
        modifier.use_bone_envelopes = settings["use_bone_envelopes"]
        modifier.use_deform_preserve_volume = settings["use_deform_preserve_volume"]
        modifier.show_viewport = settings["show_viewport"]
        modifier.show_render = settings["show_render"]
    rig["marksman_t_pose_rest_v1"] = True
    return True


rig = _target_rig()
changed = build_open_t_pose(rig)
print("T_POSE_RESULT", rig.name, changed, len(rig.data.bones), rig.get("marksman_t_pose_rest_v1"))
